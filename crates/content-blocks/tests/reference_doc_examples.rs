#[test]
fn reference_doc_side_examples_build() {
    // Additional section 3 examples: single-span text and plain-span lists.
    let (bullets, ordered) = list_helper_examples();
    let extras: Vec<Block> = blocks![text_plain_example(), bullets, ordered];
    validate_blocks(&extras).expect("side examples validate");

    // Dynamic section 3 table path; mismatched column counts fail at runtime.
    let table = table_dynamic_example(vec!["商品".to_string()], vec![vec!["りんご".to_string()]])
        .expect("row width matches columns");
    Block::from(table)
        .validate()
        .expect("dynamic table validates");
    assert!(
        table_dynamic_example(vec!["a".to_string(), "b".to_string()], vec![vec!["only-one".to_string()]]).is_err(),
        "doc §8-7: mismatched row width is rejected"
    );

    // Section 5 URL rules: destinations are unrestricted, but URL hygiene still applies.
    Block::from(Link::new("詳細", "https://any-host.example.org/promo"))
        .validate()
        .expect("any https host is allowed");
    assert!(
        Block::from(Link::new("詳細", "https://support.example.com@evil.example.org/"))
            .validate()
            .is_err(),
        "doc §8-2: a URL with userinfo is rejected"
    );
}
