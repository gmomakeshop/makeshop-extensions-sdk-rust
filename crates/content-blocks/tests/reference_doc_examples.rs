/// Local copies of the `content-fragment` and `output` types used to test the section 2
/// quickstart without adding a dependency on this crate. The field names and types match
/// `bindings::exports::makeshop::runtime::order_completed_content_hook::{ContentFragment, Output}`
/// as generated by `wit_bindgen` from `wit/order-completed-content.wit`.
struct ContentFragment {
    placement: String,
    blocks_json: String,
}

struct Output {
    schema_version: u32,
    fragments: Vec<ContentFragment>,
    #[allow(dead_code)]
    data: Vec<()>,
}

/// Quickstart from section 2.
fn quickstart() -> Output {
    let page: Vec<Block> = blocks![Heading::new(1, "ご注文ありがとうございます")];
    let blocks_json = blocks_to_json(&page);

    Output {
        schema_version: content_blocks::SCHEMA_VERSION,
        fragments: vec![ContentFragment {
            placement: "main".to_string(),
            blocks_json,
        }],
        data: vec![],
    }
}

