#[test]
fn quickstart_builds_an_output() {
    // Section 2 quickstart: builder -> blocks_to_json -> ContentFragment -> Output.
    let output = quickstart();
    assert_eq!(output.schema_version, content_blocks::SCHEMA_VERSION);
    assert_eq!(output.fragments.len(), 1);
    assert_eq!(output.fragments[0].placement, "main");
    assert!(
        output.fragments[0]
            .blocks_json
            .contains(r#""type":"heading""#)
    );
}

